// Generate the CLI serializer from Core's canonical rich-text owner. No forks.
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(root, '../assign-core/internal/richtext');
const output = path.join(root, 'internal/generated/richtext');
const check = process.argv.includes('--check');
const files = (await readdir(source)).filter(name => name.endsWith('.go') && !name.endsWith('_test.go')).sort();
const manifest = { schema: 'assign.cli.canonical-richtext.v1', owner: 'assign-core/internal/richtext', files: [] };
if (!check) await mkdir(output, { recursive: true });
for (const name of files) {
  const input = await readFile(path.join(source, name), 'utf8');
  const sha256 = createHash('sha256').update(input).digest('hex');
  manifest.files.push({ name, sha256 });
  const generated = `// Code generated by scripts/generate-richtext.mjs from assign-core/internal/richtext/${name}; DO NOT EDIT.\n// Canonical source SHA256: ${sha256}\n${input}`;
  if (check) {
    if (await readFile(path.join(output, name), 'utf8') !== generated) throw new Error(`Stale serializer: ${name}`);
  } else await writeFile(path.join(output, name), generated);
}
const unexpected = (await readdir(output)).filter(name => name.endsWith('.go') && !files.includes(name));
if (unexpected.length) throw new Error(`Unexpected generated serializer files: ${unexpected.join(', ')}`);
const encoded = JSON.stringify(manifest, null, 2) + '\n';
const manifestPath = path.join(output, 'source.json');
if (check) {
  if (await readFile(manifestPath, 'utf8') !== encoded) throw new Error('Stale serializer source manifest');
} else await writeFile(manifestPath, encoded);
console.log(`${check ? 'Checked' : 'Generated'} ${files.length} canonical serializer files`);
