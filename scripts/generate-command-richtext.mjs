// Pin the read-only TS projection to the same authoritative Go inputs.
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('internal/generated/richtext/source.json',root),'utf8'));
for (const file of manifest.files) {
  const generated = await readFile(new URL('internal/generated/richtext/'+file.name,root),'utf8');
  const source = generated.split('\n').slice(2).join('\n');
  if (createHash('sha256').update(source).digest('hex') !== file.sha256) throw new Error('stale Core source: '+file.name);
}
const outputs = {
  'command/src/richtext-source.json': JSON.stringify(manifest,null,2)+'\n',
};
const source = await readFile(new URL('internal/generated/richtext/document.go',root),'utf8');
outputs['command/src/richtext-limits.ts'] = '// Generated by scripts/generate-command-richtext.mjs; DO NOT EDIT.\n'+['SchemaVersion','TableSchemaVersion','MaxDepth','MaxNodes'].map(name => {
  const match = source.match(new RegExp('(?:const )?'+name+'\\s*=\\s*([0-9_]+)'));
  if (!match) throw new Error('missing canonical limit: '+name);
  return 'export const '+name+' = '+match[1]+';\n';
}).join('');
for (const [name,content] of Object.entries(outputs)) {
  const url = new URL(name,root);
  if (process.argv.includes('--check')) { if (await readFile(url,'utf8') !== content) throw new Error('stale '+name); }
  else await writeFile(url,content);
}
console.log('Checked canonical source hashes and TypeScript projection inputs');
